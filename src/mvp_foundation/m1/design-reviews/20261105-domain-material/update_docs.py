def read(path):
    return (BASE / path).read_text(encoding='utf-8-sig')

def section(text, start, end, value):
    a, b = text.index(start), text.index(end)
    return text[:a] + value.strip() + '\n\n' + text[b:]

def header(text, field, value):
    pattern = rf'^> \*\*{re.escape(field)}\*\*：.*$'
    text, count = re.subn(pattern, lambda m: f'> **{field}**：{value}<br>', text, count=1, flags=re.M)
    assert count == 1, field
    return text

