// Namespace retained flow styles so they cannot restyle the V2 admin shell.
import postcss from 'postcss';
import { readFile, writeFile } from 'node:fs/promises';
const files = ['style.css', 'foundation.css'];
let output = '/* Generated by scripts/build-legacy-styles.mjs; retained workflow styles only. */\n';
for (const file of files) {
  const css = postcss.parse(await readFile(new URL(`../src/${file}`, import.meta.url), 'utf8'));
  css.walkRules(rule => {
    if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map(selector =>
      /^(:root|html|body)(\s|$)/.test(selector)
        ? selector.replace(/^(:root|html|body)/, '.legacy-workflows')
        : `.legacy-workflows ${selector}`);
  });
  output += css.toString() + '\n';
}
await writeFile(new URL('../src/integrated/admin/legacy-workflows.css', import.meta.url), output);
