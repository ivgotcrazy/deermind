import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { createPreviewServer } from '../scripts/serve.mjs';

test('学生持续聊天的活动路径、边界提示与恢复',async t=>{
  const server=createPreviewServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch();
  t.after(async()=>{await browser.close();await new Promise(r=>server.close(r));});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[],api=[];
  page.on('pageerror',e=>errors.push(e.message));
  await context.route('**/api/**',r=>{api.push(r.request().url());return r.abort();});
  const base='http://127.0.0.1:'+server.address().port;
  const b=name=>page.getByRole('button',{name,exact:true});
  const heading=page.getByLabel('当前活动',{exact:true});
  const notices=page.locator('.activity-notice');
  const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('deermind-m1-student-trial-space-v1')));
  const say=async text=>{await page.locator('#student-prompt').fill(text);await b('发送').click();};
  await mkdir('test-results/student-activity-heading',{recursive:true});
  const shot=name=>page.screenshot({path:`test-results/student-activity-heading/${name}.png`});
  await page.goto(base+'/student/?mode=records');
  await page.getByLabel('教材',{exact:true}).selectOption('BNU-6A');
  await page.getByLabel('学习目标').selectOption({index:1});await b('创建并进入教材').click();

  await t.test('自由交谈转讲解；局部追问不创建子活动',async()=>{
    await say('你好');await expect(heading).toContainText('自由交谈');
    await say('讲讲增加四分之一');await expect(heading.locator('[aria-current]')).toHaveText('讲解');
    await expect(notices.filter({hasText:'本次自由交谈已结束'})).toHaveCount(1);
    const before=await saved();await b('为什么能写成乘法？').click();
    assert.equal((await saved()).activities.length,before.activities.length);
    await expect(page.locator('.equation').last()).toContainText('(1 + ¼)');
  });
  await t.test('答疑路径和返回，刷新及回看历史不改变当前标题',async()=>{
    await b('先问一个相关问题').click();
    await expect(heading.locator('[aria-current]')).toHaveText('答疑');
    await expect(heading).toContainText('讲解：增加四分之一');
    await expect(heading).toContainText('分母为什么不能为零');
    await shot('01-question-path');
    const count=await notices.count();await page.reload();
    await expect(notices).toHaveCount(count);await expect(heading.locator('[aria-current]')).toHaveText('答疑');
    await page.locator('.transcript').evaluate(el=>el.scrollTop=0);
    await expect(heading.locator('[aria-current]')).toHaveText('答疑');
    await b('回到原来的主线').click();
    await expect(heading.locator('[aria-current]')).toHaveText('讲解');
    await expect(notices.filter({hasText:'答疑结束，继续刚才的讲解'})).toHaveCount(1);
    await shot('02-return-to-explanation');
  });
  await t.test('新顶层交流保留旧树，可继续旧活动且没有双活叶节点',async()=>{
    const prior=(await saved()).activeId;
    await say('换个话题，聊聊天');await expect(heading.locator('[aria-current]')).toHaveText('自由交谈');
    const switched=await saved();assert.equal(switched.activities.find(a=>a.id===switched.activeId)?.parentId,undefined);
    await notices.filter({hasText:'已保留讲解进度'}).getByRole('button').click();
    assert.equal((await saved()).activeId,prior);
    assert.equal((await saved()).activities.filter(a=>a.status==='进行中').length,1);
    await expect(heading.locator('[aria-current]')).toHaveText('讲解');
    await b('暂停学习').click();await expect(heading).toContainText('已暂停');
    await page.locator('#student-prompt').count().then(n=>assert.equal(n,0));
    const count=await notices.count();await page.reload();await expect(notices).toHaveCount(count);
    await b('继续刚才的学习').first().click();await expect(heading).not.toContainText('已暂停');
  });
  await t.test('检测轮求助先结束再讲解；回到检测不重开旧轮',async()=>{
    await say('我想检测');await b('开始检测').click();
    await expect(heading).toContainText('第1题 · 独立作答中');
    await page.getByLabel('我的答案（本）').fill('120 ÷ 4');
    await b('结束检测并求助').click();
    await expect(heading).toContainText('第1题 · 本轮已结束');
    await expect(notices.filter({hasText:'第1题检测轮已结束'})).toHaveCount(1);
    await expect(page.getByRole('log')).not.toContainText('120 ÷ 4 = 30');
    await b('讲讲刚才这道题').click();
    await expect(heading.locator('[aria-current]')).toHaveText('讲解');
    await expect(heading).toContainText('检测：增加四分之一检测');
    await shot('03-check-help');
    await b('回到原来的主线').click();
    await expect(heading.locator('[aria-current]')).toHaveText('检测');
    await expect(notices.filter({hasText:'讲解结束，回到检测，查看本轮结果'})).toHaveCount(1);
    await expect(b('提交作答')).toHaveCount(0);
    await b('用新题重新确认').click();
    await expect(heading).toContainText('第2题 · 独立作答中');
    await page.getByLabel('我的答案（升）').fill('60');
    await b('暂停学习').click();await page.reload();await b('继续刚才的学习').first().click();
    await expect(page.getByLabel('我的答案（升）')).toHaveValue('60');
    await b('提交作答').click();await b('结束本次检测').click();
    await expect(heading.locator('[aria-current]')).toHaveText('讲解');
    const checks=(await saved()).turns.filter(t=>t.check);
    assert.equal(checks.length,2);assert.equal(checks[0].check.status,'help');
  });
  await t.test('根活动结束后不自动开闲聊或显示掌握，旧按钮不再执行',async()=>{
    await b('结束当前活动').click();await expect(heading).toHaveText('对话');
    const data=await saved();assert.equal(data.activeId,undefined);
    await expect(notices.filter({hasText:'本次讲解已结束'})).toContainText('不代表已经掌握');
    await expect(b('先问一个相关问题')).toHaveCount(0);
    await shot('04-completed');
  });
  await t.test('深层路径可展开查看，不能点击跳过活动；窄屏不横向溢出',async()=>{
    await say('讲讲增加四分之一');
    await say('分母为什么不能为零？');await say('分母为什么不能为零？');await say('分母为什么不能为零？');
    await expect(b('展开完整活动路径')).toBeVisible();
    await b('展开完整活动路径').click();
    await expect(heading.locator('.path-parent')).toHaveCount(3);
    await expect(heading.getByRole('button')).toHaveCount(1);
    await page.setViewportSize({width:390,height:844});
    await shot('05-narrow-expanded-path');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await b('收起路径').click();await b('收起对话').click();
    await b('展开对话').click();await expect(heading.locator('[aria-current]')).toHaveText('答疑');
  });
  assert.deepEqual(errors,[]);assert.deepEqual(api,[]);
});
