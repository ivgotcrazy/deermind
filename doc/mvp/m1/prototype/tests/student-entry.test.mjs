import test from 'node:test';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium, expect } from '@playwright/test';
import { createPreviewServer } from '../scripts/serve.mjs';

test('学生从书页发问，翻页后保留问题出处、对话和草稿', async t => {
  const server = createPreviewServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const browser = await chromium.launch();
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport:{width:1120,height:760} });
  const output = fileURLToPath(new URL('../test-results/student-entry/', import.meta.url));
  await mkdir(output, {recursive:true});
  await page.goto('http://127.0.0.1:' + server.address().port + '/student/?mode=records');
  const button = name => page.getByRole('button', {name,exact:true});
  await expect(button('创建并进入教材')).toBeDisabled();
  await page.getByLabel('教材',{exact:true}).selectOption('BNU-6A');
  await page.getByLabel('学习目标').selectOption({index:1});
  await button('创建并进入教材').click();
  const prompt = page.getByRole('textbox');
  await expect(prompt).toBeVisible();
  await expect(page.getByRole('log')).toHaveCount(0);
  await expect(button('展开对话')).toBeVisible();
  await expect(page.getByRole('navigation')).toHaveCount(0);
  await prompt.fill('这页没看懂，讲讲三个小组的人数。');
  await button('发送').click();
  const transcript = page.getByRole('log');
  await expect(transcript).toContainText('不同小组之间的关系');
  await expect(transcript).toContainText('第 49 页');
  const image = page.getByRole('img');
  await expect(image).toHaveAttribute('src','/materials/bnu6a/page-49.png');
  await expect.poll(() => image.evaluate(img => img.naturalWidth)).toBeGreaterThan(0);
  await page.screenshot({path:output+'book-and-conversation.png'});
  await button('下一页').click();
  await prompt.fill('为什么要先求中间量？');
  await page.reload();
  await expect(prompt).toHaveValue('为什么要先求中间量？');
  await expect(image).toHaveAttribute('src','/materials/bnu6a/page-50.png');
  await expect(transcript).toContainText('第 49 页');
  const paper = page.locator('.paper');
  await paper.evaluate(el => el.scrollTop = (el.scrollHeight - el.clientHeight) / 2);
  await button('收起教材').click();
  await expect(image).toHaveCount(0);
  await expect(transcript).toBeVisible();
  await page.reload();
  await expect(button('展开教材')).toBeVisible();
  await expect(prompt).toHaveValue('为什么要先求中间量？');
  await button('发送').click();
  await expect(image).toHaveCount(0);
  await button('展开教材').click();
  await expect(image).toHaveAttribute('src','/materials/bnu6a/page-50.png');
  await expect.poll(() => paper.evaluate(el => el.scrollTop / (el.scrollHeight - el.clientHeight))).toBeCloseTo(0.5,1);
  await prompt.fill('草稿');
  await button('收起对话').click();
  await page.reload();
  await expect(button('展开对话')).toBeVisible();
  await expect(transcript).toHaveCount(0);
  await page.getByLabel('章节').selectOption('建设适老社会（一）');
  await expect(prompt).toHaveValue('草稿');
  await expect(button('回到可讲解章节')).toHaveCount(0);
  await button('展开对话').click();
  await expect(prompt).toHaveValue('草稿');
  await expect(transcript.locator('article')).toHaveCount(2);
  // Existing spaces from the two-menu version retain the conversation and draft.
  await page.evaluate(() => {
    const key = 'deermind-m1-student-trial-space-v1';
    const space = JSON.parse(localStorage.getItem(key));
    delete space.layout;
    space.teaching = true;
    localStorage.setItem(key,JSON.stringify(space));
  });
  await page.reload();
  await expect(transcript.locator('article')).toHaveCount(2);
  await expect(button('收起教材')).toBeVisible();
});

test('聊天内讲解、追问、答题与求助（四分之一 mock）',async t=>{
  const server=createPreviewServer();
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const browser=await chromium.launch();
  t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1120,height:760}});
  await page.goto('http://127.0.0.1:'+server.address().port+'/student/?mode=records');
  const button=name=>page.getByRole('button',{name,exact:true});
  await page.getByLabel('教材',{exact:true}).selectOption('BNU-6A');
  await page.getByLabel('学习目标').selectOption({index:1});
  await button('创建并进入教材').click();
  await button('讲讲增加四分之一').click();
  await expect(page.locator('.equation')).toContainText('100 本');
  await button('没懂，画给我看').click();
  await expect(page.locator('.fraction-strip')).toHaveText('20202020+20');
  const output=fileURLToPath(new URL('../test-results/student-entry/',import.meta.url));
  await mkdir(output,{recursive:true});
  await page.screenshot({path:output+'quarter-diagram.png'});
  await button('为什么能写成乘法？').click();
  await expect(page.locator('.equation').last()).toContainText('(1 + ¼)');
  await button('我想测一下').click();
  await expect(page.locator('.test-card')).toHaveCount(0);
  await button('开始检测').click();
  const first=page.locator('.test-card').first();
  await expect(first).not.toContainText('150');
  await expect(button('提交作答')).toBeDisabled();
  await first.getByLabel('我的答案（本）').fill('120 ÷ 4');
  await page.screenshot({path:output+'quarter-answer.png'});
  await page.reload();
  await expect(first.getByLabel('我的答案（本）')).toHaveValue('120 ÷ 4');
  await button('结束检测并求助').click();
  await expect(first).toContainText('本轮已结束');
  await expect(first).toContainText('未提交的草稿');
  await expect(first).toContainText('120 ÷ 4');
  await expect(first).toContainText('草稿已保留');
  await expect(first.getByRole('textbox')).toHaveCount(0);
  await button('用图再讲一次').click();
  await expect(page.locator('figure').last()).toContainText('每格 30 本');
  await button('我想测一下').click();
  await button('开始检测').click();
  const second=page.locator('.test-card').last();
  await expect(second).toContainText('48 升');
  await second.getByLabel('我的答案（升）').fill('60');
  await button('提交作答').click();
  await button('结束本次检测').click();
  await expect(second).toContainText('结果正确');
  await expect(second).toContainText('理由与个人掌握尚未交给真实评价模型判断');
  // The finished child detection no longer offers actions on its old answer card.
  await expect(second.getByRole('button')).toHaveCount(0);
  await button('暂停学习').click();
  await expect(page.getByRole('log')).toContainText('已暂停讲解');
});
