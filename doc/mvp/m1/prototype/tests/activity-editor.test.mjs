import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { createPreviewServer } from '../scripts/serve.mjs';

test('三类活动独立配置、节点继承及流程分支',async t=>{
  const server=createPreviewServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch();t.after(async()=>{await browser.close();await new Promise(r=>server.close(r));});
  const page=await browser.newPage({viewport:{width:1600,height:1700}}),errors=[];
  page.setDefaultTimeout(6000);page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:'+server.address().port;
  const b=name=>page.getByRole('button',{name,exact:true});
  await mkdir('test-results/activity-editor',{recursive:true});
  for(const [kind,name,first] of [['question','答疑','定位问题'],['assessment','检测','准备检测'],['free','自由交谈','交流与澄清']]){
    await page.goto(base+'/admin/#/interaction?kind='+kind);
    await expect(b(name+'蓝图')).toBeVisible();
    await expect(b('编辑流程节点')).toHaveCount(0);
    await expect(page.getByText('流程转移条件',{exact:true})).toHaveCount(0);
    await b('结束节点（预置）').click();await expect(b('编辑节点')).toHaveCount(0);
    await b('开始节点（预置）').click();await b('编辑条件转移').click();
    await page.getByLabel('何时判断',{exact:true}).fill(name+'请求已确认后判断');
    await b('应用到草稿').click();await b('保存蓝图').click();await page.reload();
    await b('开始节点（预置）').click();
    await expect(page.getByLabel('节点条件转移')).toContainText(name+'请求已确认后判断');
    await b('节点 1：'+first).click();await b('编辑节点').click();
    await expect(page.getByLabel('继承的活动规则（只读）',{exact:true})).toHaveCount(0);
    await expect(page.getByLabel('继承的活动推荐策略（只读）',{exact:true})).toHaveCount(0);
    await page.getByLabel('无法继续时的处理',{exact:true}).fill('');await b('应用到草稿').click();
    await expect(page.getByRole('alert')).toContainText('无法继续');await b('取消').click();
    await b('活动规则').click();await b('新增规则').click();
    await page.getByLabel('规则名称',{exact:true}).fill(name+'补充约束');
    await page.getByLabel('适用情况',{exact:true}).fill('开始处理本节点时');
    await page.getByLabel('具体要求',{exact:true}).fill('保留本节点未解决内容，不覆盖其他活动。');
    await page.getByLabel('依据与限制',{exact:true}).fill('Mock 配置走查');await b('保存').click();
    await expect(page.locator('.rule-table tr').filter({hasText:name+'补充约束'})).toContainText('未引用');
    await b(name+'蓝图').click();await b('编辑节点').click();
    await page.getByRole('checkbox',{name:name+'补充约束',exact:true}).check();
    await b('应用到草稿').click();await b('保存蓝图').click();await page.reload();
    await expect(page.getByLabel('本节点规则',{exact:true})).toContainText(name+'补充约束');
    await b('活动规则').click();await b('选择活动规则').click();
    await page.getByRole('checkbox',{name:name+'补充约束',exact:true}).check();await b('保存活动配置').click();
    await b(name+'蓝图').click();await expect(page.getByLabel('本节点规则',{exact:true})).not.toContainText(name+'补充约束');
    await b('编辑节点').click();await expect(page.getByRole('checkbox',{name:name+'补充约束',exact:true})).toHaveCount(0);await b('取消').click();
    await b('活动推荐策略').click();await b('选择活动推荐策略').click();
    const option=page.getByRole('dialog').getByRole('checkbox').last();const strategyName=await option.locator('..').innerText();
    await option.check();await b('保存活动配置').click();await page.reload();
    await expect(page.getByLabel('当前活动推荐',{exact:true})).toContainText(strategyName);
    assert.equal(new URL(page.url()).hash.includes('kind='+kind),true);
    await b(name+'蓝图').click();
    await expect(page.getByRole('heading',{name:name+'活动',exact:true})).toBeVisible();
    await expect(page.getByLabel('继承的活动推荐策略',{exact:true})).toHaveCount(0);
    await page.screenshot({path:'test-results/activity-editor/'+kind+'.png'});
  }
  await page.goto(base+'/admin/#/interaction?kind=question');
  await page.getByRole('button',{name:/连接：调用讲解或子答疑 → 回应问题/}).click();
  await expect(page.getByLabel('蓝图定义详情')).toContainText('返回“回应问题”');
  await expect(page.getByLabel('节点条件转移')).toContainText('暂停时仍等待');
  await b('活动规则').click();await expect(page.locator('.rule-table')).not.toContainText('检测补充约束');
  await page.goto(base+'/admin/#/interaction?kind=assessment');
  await b('节点 2：检测轮').click();
  await expect(page.getByLabel('本节点规则',{exact:true})).toContainText('求助先结束本轮');
  await expect(page.getByLabel('节点条件转移')).toContainText('未结束本轮不能');
  await page.getByRole('button',{name:/连接：轮后处理 → 准备检测/}).click();
  await expect(page.getByLabel('节点条件转移')).toContainText('不恢复旧轮或旧题单');
  await page.goto(base+'/admin/#/interaction?kind=free');
  await b('节点 2：转交学习活动').click();
  await expect(page.getByLabel('蓝图定义详情')).toContainText('顶层');
  await expect(page.getByLabel('节点条件转移')).toContainText('创建失败');
  await b('活动推荐策略').click();await b('新建策略').click();
  await page.getByLabel('策略名称',{exact:true}).fill('自由交谈新策略');
  for(const label of ['策略目的','适用情况','不适用情况','需要的信息','如何开展','允许的帮助','需要观察的表现','调整方式','结束条件','依据与限制','领域示例'])await page.getByLabel(label,{exact:true}).fill('针对当前交流目的，必要时简短澄清；不能产生能力结论。');
  await b('保存').click();await expect(page.getByRole('heading',{name:'自由交谈新策略',exact:true})).toBeVisible();
  await page.reload();assert.ok(page.url().includes('kind=free'));
  await page.goto(base+'/admin/#/interaction?kind=explanation&tab=rules');
  await expect(page.locator('.rule-table')).not.toContainText('补充约束');
  assert.deepEqual(errors,[]);
});
