import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { createPreviewServer } from '../scripts/serve.mjs';

test('讲解活动与节点配置的继承、保存及旧配置保留',async t=>{
  const server=createPreviewServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch();t.after(async()=>{await browser.close();await new Promise(r=>server.close(r));});
  const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[];
  page.setDefaultTimeout(6000);page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:'+server.address().port;
  const b=name=>page.getByRole('button',{name,exact:true});
  await page.goto(base+'/admin/#/interaction?tab=blueprint');
  await expect(page.getByLabel('继承的活动规则',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('本节点规则',{exact:true})).toContainText('说明关键关系');
  await expect(page.getByLabel('继承的活动推荐策略',{exact:true})).toHaveCount(0);
  await b('编辑节点').click();
  await expect(page.getByLabel('继承的活动规则（只读）',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('继承的活动推荐策略（只读）',{exact:true})).toHaveCount(0);
  await expect(page.getByRole('dialog').getByRole('checkbox',{name:'表达不直接等于掌握'})).toHaveCount(0);
  await page.getByLabel('允许动作',{exact:true}).fill('');await b('应用到草稿').click();
  await expect(page.getByRole('alert')).toContainText('允许动作');
  await page.getByLabel('允许动作',{exact:true}).fill('可以换一种图示解释，仍须遵守活动规则。');
  await page.getByLabel('无法继续时的处理',{exact:true}).fill('无法核实则停止该段解释，保留未解决内容。');
  await page.getByRole('checkbox',{name:'根据表现调整帮助',exact:true}).check();
  await b('应用到草稿').click();await b('保存蓝图').click();await page.reload();
  await expect(page.getByLabel('本节点规则',{exact:true})).toContainText('根据表现调整帮助');
  await expect(page.getByLabel('蓝图定义详情')).toContainText('可以换一种图示解释');
  await b('开始节点（预置）').click();
  await expect(page.getByLabel('继承的活动推荐策略',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('继承的活动规则',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('本节点规则',{exact:true})).toHaveCount(0);

  await b('活动规则').click();await b('新增规则').click();
  await page.getByLabel('规则名称',{exact:true}).fill('核对引用事实');
  await page.getByLabel('适用情况',{exact:true}).fill('引用材料事实时');
  await page.getByLabel('具体要求',{exact:true}).fill('不确定时先核对材料。');
  await page.getByLabel('依据与限制',{exact:true}).fill('仅作 mock 配置走查。');
  await page.getByRole('dialog').getByRole('button',{name:'保存',exact:true}).click();
  const ruleRow=page.locator('.rule-table tbody tr').filter({hasText:'核对引用事实'});
  await expect(ruleRow).toContainText('未引用');
  await b('选择活动规则').click();await page.getByRole('checkbox',{name:'核对引用事实',exact:true}).check();
  await b('取消').click();await expect(ruleRow).toContainText('未引用');
  await b('选择活动规则').click();await page.getByRole('checkbox',{name:'核对引用事实',exact:true}).check();
  await b('保存活动配置').click();await expect(ruleRow).toContainText('所有节点');
  await b('讲解蓝图').click();
  await expect(page.getByLabel('继承的活动规则',{exact:true})).toHaveCount(0);
  await b('活动规则').click();await b('编辑规则：核对引用事实').click();
  await page.getByLabel('具体要求',{exact:true}).fill('必须核对来源，信息不足时先澄清。');
  await page.getByRole('dialog').getByRole('button',{name:'保存',exact:true}).click();
  await b('停用规则：核对引用事实').click();
  await page.reload();
  const inherited=page.getByLabel('当前活动规则',{exact:true});
  await inherited.getByText('核对引用事实',{exact:false}).first().click();
  await expect(inherited).toContainText('已停用 · 不生效');
  await expect(inherited).toContainText('必须核对来源');

  await b('活动推荐策略').click();await b('选择活动推荐策略').click();
  await page.getByRole('checkbox',{name:'对比辨析',exact:true}).check();await b('保存活动配置').click();
  await page.reload();
  await expect(page.getByLabel('当前活动推荐',{exact:true})).toContainText('对比辨析');
  await b('讲解蓝图').click();
  await expect(page.getByLabel('继承的活动推荐策略',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('本节点推荐策略',{exact:true})).not.toContainText('对比辨析');
  await b('编辑节点').click();
  await expect(page.getByRole('dialog').getByRole('checkbox',{name:'对比辨析',exact:true})).toHaveCount(0);
  await b('取消').click();
  await mkdir('test-results/teaching-scope',{recursive:true});
  await page.screenshot({path:'test-results/teaching-scope/node.png',fullPage:true});
  await b('活动规则').click();await page.screenshot({path:'test-results/teaching-scope/rules.png',fullPage:true});

  await page.evaluate(()=>{
    const key='deermind-m1-teaching-v1',saved=JSON.parse(localStorage.getItem(key));
    delete saved.activityRules;delete saved.activityStrategies;
    const node=saved.blueprint.stages.find(n=>n.id==='teach');
    node.name='保留旧节点';delete node.actions;delete node.blocked;delete node.rules;
    saved.blueprint.transitions[0].condition='保留旧条件';
    localStorage.setItem(key,JSON.stringify(saved));
  });
  await page.goto(base+'/admin/#/interaction?tab=blueprint');await page.reload();
  await expect(page.getByLabel('蓝图定义详情')).toContainText('保留旧节点');
  await expect(page.getByLabel('蓝图定义详情')).toContainText('内容无法核实');
  await b('开始节点（预置）').click();await expect(page.getByLabel('节点条件转移')).toContainText('保留旧条件');
  await page.goto(base+'/admin/#/interaction?kind=question');
  await expect(b('选择活动规则')).toHaveCount(0);
  await expect(b('编辑节点')).toBeVisible();
  assert.deepEqual(errors,[]);
});
