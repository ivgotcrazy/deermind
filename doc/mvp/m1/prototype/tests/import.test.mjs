import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { chromium, expect as baseExpect } from '@playwright/test';
import { createPreviewServer } from '../scripts/serve.mjs';

const output = fileURLToPath(new URL('../test-results/d01/', import.meta.url));
const expect = baseExpect.configure({ timeout: 12000 });

test('standalone M1 import and organization retain sources, corrections and isolated drafts', async t => {
  await mkdir(output, { recursive: true });
  const server = createPreviewServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = 'http://127.0.0.1:' + server.address().port;
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
  await context.addInitScript(() => localStorage.setItem('deermind-next-textbook-import-v1', 'old-prototype-sentinel'));
  const page = await context.newPage();
  const errors = [], apiAttempts = [], captures = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/api/**', route => { apiAttempts.push(route.request().url()); return route.abort(); });
  t.after(async () => { await browser.close(); await new Promise(resolve => server.close(resolve)); });
  const btn = name => page.getByRole('button', { name, exact: true });
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('deermind-m1-import-v1') || '[]'));
  const tree = name => page.locator('.material-tree-item').filter({ has: page.locator('span', { hasText: name }) });
  const shot = async (id, title, locator) => {
    await page.evaluate(() => document.fonts.ready);
    const bytes = await (locator || page).screenshot({ path: output + id + '.png', animations: 'disabled' });
    captures.push({ id, title, file: id + '.png', url: page.url(), sha256: createHash('sha256').update(bytes).digest('hex'), viewport: page.viewportSize() });
  };
  let retainedId;

  await t.test('textbook entry remains available beside domain management; file limitations are explicit', async () => {
    await page.goto(base + '/admin/#/textbooks');
    await expect(page.getByRole('navigation', { name: '后台导航' }).getByRole('button')).toHaveCount(2);
    await expect(page.getByText('先导入第一份教材', { exact: true })).toBeVisible();
    await shot('D01-S01', 'M1教材入口与空白状态');
    await btn('导入教材').click();
    await expect(btn('上传并开始整理')).toBeDisabled();
    await btn('新建领域').click();
    await page.getByLabel('领域名称', { exact: true }).fill('小学数学');
    await btn('创建并选用').click();
    await btn('上传并开始整理').click();
    await expect(page.getByRole('alert')).toContainText('请先选择');
    await page.locator('input[type=file]').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('not a scan') });
    await expect(page.getByRole('alert')).toContainText('请选择PDF');
    await page.locator('input[type=file]').setInputFiles({ name: 'scan.png', mimeType: 'image/png', buffer: Buffer.from([1, 2, 3]) });
    await btn('上传并开始整理').click();
    await expect(page.getByRole('alert')).toContainText('未接入OCR');
    assert.equal((await state())[0].state, 'upload');
    await btn('载入真实教材书页').click();
    await expect(page.getByRole('alert')).toHaveCount(0);
    await expect(page.locator('.upload-files tbody tr')).toHaveCount(5);
    await btn('上移 北师大六上-书页50.png').click();
    await expect(page.locator('.upload-files tbody tr').first()).toContainText('书页50');
    await btn('下移 北师大六上-书页50.png').click();
    await shot('D01-S02', '内置五页与教材信息');
    await btn('上传并开始整理').scrollIntoViewIfNeeded();
    await shot('D01-S02-B', '文件与开始整理');
    retainedId = (await state())[0].id;
    checks.push('Textbook navigation remains available; invalid inputs and unconnected OCR do not fabricate recognized content');
  });

  await t.test('mock interruption and retry keep one import and real source images', async () => {
    await page.getByText('Mock处理场景', { exact: true }).click();
    await page.getByLabel('模拟一次识别中断').check();
    await btn('上传并开始整理').click();
    await expect(page.getByRole('progressbar')).toBeVisible();
    await shot('D01-S03', 'M1模拟整理进度');
    await expect(page.getByRole('alert')).toContainText('模拟识别中断');
    await shot('D01-S03-F', '中断后继续同一导入');
    await btn('继续整理').click();
    await expect(btn('原页核对')).toBeVisible();
    await btn('原页核对').click();
    await expect(page.locator('.material-organizer')).toBeVisible();
    await page.locator('.source-paper img').evaluate(image => image.decode());
    assert.equal((await state()).length, 1);
    assert.equal((await state())[0].id, retainedId);
    await shot('D01-S04', '目录、原页与图文工作区');
    checks.push('Interrupted mock processing resumes the same batch; actual bundled source image loads');
  });

  await t.test('cross-page merge and question preview preserve teaching roles', async () => {
    await btn('确认本课整理结果').click();
    await expect(page.getByRole('alert')).toContainText('合并');
    await page.getByRole('alert').scrollIntoViewIfNeeded();
    await shot('D01-S05', '未处理跨页疑点不能确认');
    await btn('合并内容').click();
    await page.getByLabel('要并入的内容').selectOption('MAT-METHODS');
    await shot('D01-S06', '选择跨页两种解法', page.getByRole('dialog'));
    await btn('确认合并').click();
    await page.locator('[data-block="B-METHOD-A"]').scrollIntoViewIfNeeded();
    await shot('D01-S06-R', '合并后保留各自来源');
    await page.getByRole('tab', { name: '仅题目与条件', exact: true }).click();
    await expect(page.locator('[data-block="B-METHOD-A"]')).toHaveCount(0);
    await expect(page.locator('[data-block="B-HINT"]')).toHaveCount(0);
    await shot('D01-S07', '题目与条件预览');
    await page.getByRole('tab', { name: '教材原内容', exact: true }).click();
    await page.locator('[data-block="B-QUESTION"]').getByRole('button', { name: '编辑', exact: true }).click();
    await shot('D01-S08', '内容、用途与来源编辑', page.getByRole('dialog'));
    await page.getByLabel('内容名称').fill('不应保存的改名');
    await btn('取消').click();
    await expect(page.locator('[data-block="B-QUESTION"]')).toContainText('要求求出的量');
    await tree('判断并解释计算错误').click();
    await expect(page.locator('[data-block="B-ERROR-WORK"]')).toContainText('这些算式用于辨错，保留原样');
    await btn('确认本课整理结果').click();
    await page.getByRole('status').scrollIntoViewIfNeeded();
    await shot('D01-S09', '课题核对结果');
    checks.push('Cross-page methods remain separate blocks; question mode excludes assistance; cancellation and deliberately incorrect material remain intact');
  });

  await t.test('tables, chart references, draft reload and D02 handoff remain explicit', async () => {
    await tree('设计研究方案').click();
    await expect(page.locator('[data-block="B-PLAN-BLANK"] svg')).toBeVisible();
    await tree('整理与比较人口数据').click();
    await page.locator('[data-block="B-COUNTS"]').getByRole('button', { name: '编辑', exact: true }).click();
    await page.getByLabel('表头 3', { exact: true }).fill('65岁及以上人数');
    await page.getByRole('dialog').getByRole('checkbox').check();
    await shot('D01-S10', '修正表头并保留行列数据', page.getByRole('dialog'));
    await btn('保存内容').click();
    await btn('确认本课整理结果').click();
    await tree('同一组数据的三种统计图').click();
    await page.locator('[data-block="B-PIE"]').getByRole('button', { name: '编辑', exact: true }).click();
    await page.getByRole('dialog').getByRole('checkbox').check();
    await btn('保存内容').click();
    await expect(page.getByRole('alert')).toContainText('年龄占比表');
    await btn('取消').click();
    await page.locator('[data-block="B-PIE"]').getByRole('button', { name: '编辑', exact: true }).click();
    await page.getByRole('dialog').getByRole('checkbox').check();
    await page.getByLabel('关联内容', { exact: true }).selectOption(['B-AGE']);
    await shot('D01-S11', '图与跨页数据表关联', page.getByRole('dialog'));
    await btn('保存内容').click();
    await btn('确认本课整理结果').click();
    await page.locator('[data-block="B-PIE"]').scrollIntoViewIfNeeded();
    await shot('D01-S11-R', '图例和数据引用保留');
    await btn('← 返回教材列表').click();
    await shot('D01-S12', 'M1草稿列表与继续入口');
    await page.locator(`[data-import-id="${retainedId}"]`).getByRole('button', { name: /继续导入/ }).click();
    await page.reload();
    await expect(page.locator('.organizer-heading')).toContainText('3 个课题已核对');
    await tree('整理与比较人口数据').click();
    await expect(page.locator('[data-block="B-COUNTS"] table')).toContainText('65岁及以上人数');
    await btn('进入模板匹配').click();
    await expect(page.getByText('匹配或补建领域定义', { exact: true })).toBeVisible();
    await shot('D01-S13', '从原页核对进入模板匹配');
    await btn('原页核对').click();
    await page.setViewportSize({ width: 1280, height: 900 });
    assert.ok(await page.locator('.page-container').evaluate(e => e.scrollWidth <= e.clientWidth));
    await page.setViewportSize({ width: 1440, height: 1000 });
    checks.push('Table correction and cross-page chart references survive reload; handoff opens domain integration without creating objects; desktop has no horizontal overflow');
  });

  await t.test('delete is scoped; removed input and old-prototype storage stay isolated', async () => {
    await btn('← 返回教材列表').click();
    await btn('导入教材').click();
    await page.getByLabel('教材名称', { exact: true }).fill('D01取消导入示例');
    await btn('← 返回教材列表').click();
    await btn('删除导入 D01取消导入示例').click();
    await shot('D01-S14', '删除仅限本次M1草稿', page.getByRole('dialog'));
    await btn('取消').click();
    await expect(btn('继续导入 D01取消导入示例')).toBeVisible();
    await btn('删除导入 D01取消导入示例').click(); await btn('确认删除').click();
    await expect(btn('继续导入 D01取消导入示例')).toHaveCount(0);
    assert.ok((await state()).some(d => d.id === retainedId));
    await btn('导入教材').click(); await btn('载入真实教材书页').click();
    await page.getByLabel('所属领域', {exact:true}).selectOption({label:'小学数学'});
    await btn('移除 北师大六上-书页49.png').click(); await btn('上传并开始整理').click();
    await expect(btn('原页核对')).toBeVisible();
    await btn('原页核对').click();
    await expect(page.locator('.material-organizer')).toBeVisible();
    await expect(page.getByRole('button', { name: '49 页', exact: true })).toHaveCount(0);
    await btn('确认本课整理结果').click(); await expect(page.getByRole('alert')).toContainText('缺页');
    await btn('← 返回教材列表').click(); await btn('导入教材').click(); await btn('载入真实教材书页').click();
    await page.getByLabel('所属领域', {exact:true}).selectOption({label:'小学数学'});
    await btn('上传并开始整理').click(); await expect(page.getByRole('progressbar')).toBeVisible();
    await page.reload(); await expect(page.getByText('演示已暂停', { exact: true })).toBeVisible();
    await btn('继续整理').click(); await expect(btn('原页核对')).toBeVisible();
    await btn('原页核对').click();
    await expect(page.locator('.material-organizer')).toBeVisible();
    assert.equal(await page.evaluate(() => localStorage.getItem('deermind-next-textbook-import-v1')), 'old-prototype-sentinel');
    assert.deepEqual(errors, []); assert.deepEqual(apiAttempts, []);
    assert.equal((await fetch(base + '/api/chat')).status, 404);
    assert.equal((await fetch(base + '/../../package.json')).status, 404);
    checks.push('Delete affects only selected draft; absent pages are not generated; processing reload can resume; no old data or model API is used');
  });

  await writeFile(output + 'capture-manifest.json', JSON.stringify({ date: '2026-11-03', prototype: 'doc/mvp/m1/prototype', scope: 'D01 isolated mock; not OCR or full M1 acceptance', base, captures, checks, errors, apiAttempts }, null, 2) + '\n');
});
