import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { createPreviewServer } from '../scripts/serve.mjs';

test('讲解节点条件转移、预置端点及保存恢复',async t=>{
  const server=createPreviewServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch();t.after(async()=>{await browser.close();await new Promise(r=>server.close(r));});
  const page=await browser.newPage({viewport:{width:1600,height:1200}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:'+server.address().port;
  const b=name=>page.getByRole('button',{name,exact:true});
  await page.goto(base+'/admin/#/interaction?tab=blueprint');
  await expect(b('添加连接')).toHaveCount(0);
  await b('开始节点（预置）').click();
  await expect(page.getByLabel('蓝图定义详情')).toContainText('不可删除');
  await expect(b('编辑节点')).toHaveCount(0);
  await b('编辑条件转移').click();
  await page.getByLabel('何时判断',{exact:true}).fill('学生明确请求开始后判断');
  await b('应用到草稿').click();await b('保存蓝图').click();await page.reload();
  await b('开始节点（预置）').click();
  await expect(page.getByLabel('节点条件转移')).toContainText('学生明确请求开始后判断');
  await b('结束节点（预置）').click();
  await expect(b('编辑条件转移')).toHaveCount(0);
  await expect(b('编辑节点')).toHaveCount(0);
  await expect(page.getByLabel('蓝图定义详情')).toContainText('没有出向连接');

  await page.getByRole('button',{name:/连接：讲解与互动 → 检测与反馈/}).click();
  await expect(page.getByLabel('蓝图定义详情').getByRole('heading',{name:'讲解与互动',exact:true})).toBeVisible();
  await expect(page.locator('.routing-table tr.highlight')).toContainText('学生同意独立检测');
  await b('编辑条件转移').click();await b('添加条件转移').click();
  const rows=page.locator('.routing-edit-row'),last=rows.last();
  await last.getByLabel('转移名称').fill('继续解释');
  await last.getByLabel('目标节点').selectOption('teach');
  await last.getByLabel('满足什么条件').fill('学生希望继续解释当前问题。');
  await last.getByLabel('判断依据').fill('学生最新回应。');
  await page.getByLabel('没有条件命中时',{exact:true}).fill('');
  await b('应用到草稿').click();await expect(page.getByRole('alert')).toContainText('未命中');
  await page.getByLabel('没有条件命中时',{exact:true}).fill('等待学生回应，不自动重讲。');
  const count=await rows.count();
  for(let i=count-1;i>0;i--)await rows.nth(i).getByRole('button',{name:'上移',exact:true}).click();
  await expect(rows.first().getByLabel('转移名称')).toHaveValue('继续解释');
  await mkdir('test-results/node-routing',{recursive:true});
  await page.screenshot({path:'test-results/node-routing/editor.png',fullPage:true});
  await b('应用到草稿').click();await b('保存蓝图').click();await page.reload();
  await expect(page.locator('.routing-table tbody tr').first()).toContainText('继续解释');
  await expect(page.getByLabel('节点条件转移')).toContainText('等待学生回应，不自动重讲。');
  await expect(page.getByRole('button',{name:/连接：讲解与互动 → 讲解与互动/})).toBeVisible();
  await page.setViewportSize({width:1600,height:1800});
  await page.screenshot({path:'test-results/node-routing/blueprint.png',fullPage:true});

  await b('编辑条件转移').click();
  while(await rows.count())await rows.first().getByRole('button',{name:'删除',exact:true}).click();
  await b('应用到草稿').click();await expect(page.getByRole('alert')).toContainText('至少保留');await b('取消').click();
  await page.goto(base+'/admin/#/interaction?kind=question');
  await expect(b('编辑节点')).toBeVisible();
  await expect(b('编辑条件转移')).toBeVisible();
  assert.deepEqual(errors,[]);
});
