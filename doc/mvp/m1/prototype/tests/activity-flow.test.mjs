import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { createPreviewServer } from '../scripts/serve.mjs';

test('活动定义编辑及学生检测轮、子讲解和返回主线', async t=>{
  const server=createPreviewServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch();t.after(async()=>{await browser.close();await new Promise(r=>server.close(r));});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:'+server.address().port;
  const b=name=>page.getByRole('button',{name,exact:true});
  await page.goto(base+'/admin/#/interaction?kind=question');
  await expect(page.getByRole('heading',{name:'答疑活动',exact:true})).toBeVisible();
  await t.test('四类活动统一流程图，节点与连接可查看，编辑名称后连接保留',async()=>{
    for(const kind of ['explanation','question','assessment','free']){
      await page.goto(base+'/admin/#/interaction?kind='+kind);
      await expect(page.getByRole('group',{name:'活动流程图：选择节点或连接查看定义'})).toBeVisible();
      assert.ok(await page.locator('.graph-node').count()>0);
      await page.locator('.graph-node').first().click();
      await page.locator('.graph-edge[role="button"]').first().click();
      await mkdir('test-results/activity-flow',{recursive:true});
      await page.setViewportSize({width:1440,height:1800});
      await page.screenshot({path:'test-results/activity-flow/blueprint-'+kind+'.png',fullPage:true});
      await page.setViewportSize({width:1440,height:1000});
    }
    await page.goto(base+'/admin/#/interaction?kind=question');
    await page.getByRole('button',{name:/连接：调用讲解或子答疑 → 回应问题/}).click();
    await expect(page.getByLabel('蓝图定义详情')).toContainText('子活动完成');
    await page.getByRole('button',{name:'节点 1：定位问题',exact:true}).click();
    await b('编辑节点').click();
    await page.getByLabel('节点名称',{exact:true}).first().fill('定位具体问题');
    await b('应用到草稿').click();await b('保存蓝图').click();await page.reload();
    await expect(page.getByRole('button',{name:/连接：开始 → 定位具体问题/})).toBeVisible();
    await b('开始节点（预置）').click();await b('编辑条件转移').click();
    await expect(page.getByLabel('目标节点').first()).toHaveValue('locate');
    await b('取消').click();
  });
  await b('活动规则').click();await b('编辑规则：局部追问不碎裂').click();await page.getByLabel('规则名称').fill('局部追问不拆活动');await b('保存').click();
  await page.reload();await b('活动规则').click();await expect(page.getByText('局部追问不拆活动',{exact:true})).toBeVisible();
  await b('检测').click();await b('活动规则').click();await expect(page.getByText('检测轮原子性',{exact:true})).toBeVisible();
  await mkdir('test-results/activity-flow',{recursive:true});
  await page.screenshot({path:'test-results/activity-flow/admin-assessment.png',fullPage:true});
  await page.goto(base+'/student/?mode=records');
  await page.getByLabel('教材',{exact:true}).selectOption('BNU-6A');
  await page.getByLabel('学习目标').selectOption({index:1});await b('创建并进入教材').click();
  await b('讲讲增加四分之一').click();await b('先问一个相关问题').click();
  await expect(page.getByRole('log')).toContainText('分母为什么不能为零');
  await b('回到原来的主线').click();
  await page.getByRole('textbox').fill('我想检测');await b('发送').click();await b('开始检测').click();
  await page.getByLabel('我的答案（本）').fill('150');await b('提交作答').click();
  await expect(page.getByRole('log')).not.toContainText('结果正确');
  await b('下一轮').click();await page.getByLabel('我的答案（升）').fill('48 ÷ 4');
  await b('结束检测并求助').click();
  await expect(page.getByRole('log')).toContainText('本轮因求助结束');
  await expect(page.getByRole('log')).not.toContainText('48 ÷ 4 = 12');
  await b('讲讲刚才这道题').click();await expect(page.locator('figure').last()).toContainText('每格 12 升');
  await b('回到原来的主线').click();await b('用新题重新确认').click();
  await expect(page.locator('.test-card').filter({hasText:'一条彩带'})).toContainText('64 厘米');
  await b('暂停学习').click();await page.reload();await expect(page.getByRole('log')).toContainText('本轮已暂停');
  await b('继续刚才的学习').first().click();
  await page.getByLabel('我的答案（厘米）').fill('80');await b('提交作答').click();await b('结束本次检测').click();
  await page.screenshot({path:'test-results/activity-flow/student-return.png',fullPage:true});
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('deermind-m1-student-trial-space-v1')));
  const checks=saved.turns.filter(t=>t.check);
  assert.equal(checks.length,3);assert.equal(new Set(checks.map(t=>t.activityId)).size,1);
  const child=saved.activities.find(a=>a.triggerRound===checks[1].roundId);
  assert.equal(child.kind,'讲解');assert.equal(child.parentId,checks[1].activityId);
  await page.goto(base+'/admin/#/interaction?kind=trace');
  await expect(page.getByRole('navigation',{name:'活动树'})).toContainText('检测');
  await page.screenshot({path:'test-results/activity-flow/admin-trace.png',fullPage:true});
  assert.deepEqual(errors,[]);
});
